const store = new Store();

export function getTwoFAItems(): TwoFAItem[] {
    return store.get('twoFAItems', []) as TwoFAItem[];
}

export function setTwoFAItems(items: TwoFAItem[]): void {
    store.set('twoFAItems', items);
}

export function addTwoFAItem(item: Omit<TwoFAItem, 'id'>): TwoFAItem {
    const newItem: TwoFAItem = {
        ...item,
        id: generateId(),
    };
    const items = getTwoFAItems();
    items.push(newItem);
    store.set('twoFAItems', items);
    return newItem;
}

export function removeTwoFAItem(id: string): boolean {
    const items = getTwoFAItems();
    const filtered = items.filter((item) => item.id !== id);
    store.set('twoFAItems', filtered);
    return true;
}

export function updateTwoFAItem(id: string, updates: Partial<TwoFAItem>): TwoFAItem | null {
    const items = getTwoFAItems();
    const index = items.findIndex((item) => item.id === id);
    if (index >= 0) {
        items[index] = { ...items[index], ...updates };
        store.set('twoFAItems', items);
        return items[index];
    }
    return null;
}

export function mergeTwoFAItems(newItems: TwoFAItem[]): number {
    const currentItems = getTwoFAItems();
    const allItems = [...currentItems, ...newItems];
    store.set('twoFAItems', allItems);
    return newItems.length;
}

export function getAppSettings(): AppSettings {
    return store.get('appSettings', {
        minimizeToTray: false,
        runOnStartup: false,
        autoLock: true,
        autoLockTimeout: 5,
        blurOnInactive: false,
    }) as AppSettings;
}

export function setAppSettings(settings: AppSettings): void {
    store.set('appSettings', settings);
}

export function hasMasterPassword(): boolean {
    return store.has('masterPassword');
}

export function getMasterPasswordHash(): string | undefined {
    return store.get('masterPassword') as string | undefined;
}

export function setMasterPasswordHash(hash: string): void {
    store.set('masterPassword', hash);
}
